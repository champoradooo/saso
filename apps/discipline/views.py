from django.db.models import Count
from rest_framework import filters, viewsets
from rest_framework.decorators import action
from rest_framework.response import Response

from apps.students.models import Student

from .models import DisciplinaryCase
from .serializers import DisciplinaryCaseSerializer


class DisciplinaryCaseViewSet(viewsets.ModelViewSet):

    # =====================================================
    # QUERYSET
    #
    # NEWEST CASE FIRST
    # =====================================================

    queryset = (
        DisciplinaryCase.objects
        .select_related("student")
        .all()
        .order_by(
            "-created_at",
            "-id",
        )
    )

    serializer_class = DisciplinaryCaseSerializer

    # =====================================================
    # FILTERING / SEARCHING
    # =====================================================

    filter_backends = [
        filters.SearchFilter,
        filters.OrderingFilter,
    ]

    search_fields = [
        "case_number",
        "student__first_name",
        "student__last_name",
        "violation",
        "reason",
    ]

    ordering_fields = [
        "incident_date",
        "severity",
        "status",
        "created_at",
        "updated_at",
        "offense_number",
        "id",
    ]

    # =====================================================
    # DEFAULT ORDER
    # =====================================================

    ordering = [
        "-created_at",
        "-id",
    ]

    # =====================================================
    # CREATE
    #
    # Case number is auto-generated by the model.
    # =====================================================

    def perform_create(self, serializer):

        serializer.save()

    # =====================================================
    # QUERY PARAMETERS
    # =====================================================

    def get_queryset(self):

        qs = (
            DisciplinaryCase.objects
            .select_related("student")
            .all()
        )

        severity = (
            self.request.query_params
            .get("severity")
        )

        status = (
            self.request.query_params
            .get("status")
        )

        violation = (
            self.request.query_params
            .get("violation")
        )

        # -------------------------------------------------
        # SEVERITY
        # -------------------------------------------------

        if severity:
            qs = qs.filter(
                severity=severity
            )

        # -------------------------------------------------
        # STATUS
        # -------------------------------------------------

        if status:
            qs = qs.filter(
                status=status
            )

        # -------------------------------------------------
        # VIOLATION
        # -------------------------------------------------

        if violation:
            qs = qs.filter(
                violation__iexact=violation
            )

        # -------------------------------------------------
        # ALWAYS NEWEST FIRST
        # -------------------------------------------------

        qs = qs.order_by(
            "-created_at",
            "-id",
        )

        return qs

    # =====================================================
    # STUDENT DISCIPLINE HISTORY
    # =====================================================

    @action(
        detail=False,
        methods=["get"],
        url_path=r"student/(?P<student_id>\d+)/history"
    )
    def student_history(
        self,
        request,
        student_id=None
    ):

        try:

            student = Student.objects.get(
                pk=student_id
            )

        except Student.DoesNotExist:

            return Response(
                {
                    "detail": "Student not found."
                },
                status=404
            )

        # -------------------------------------------------
        # NEWEST CASE FIRST
        # -------------------------------------------------

        cases = (
            DisciplinaryCase.objects
            .select_related("student")
            .filter(
                student=student
            )
            .order_by(
                "-created_at",
                "-id",
            )
        )

        # -------------------------------------------------
        # VIOLATION SUMMARY
        # -------------------------------------------------

        summary = (
            DisciplinaryCase.objects
            .filter(
                student=student
            )
            .values(
                "violation"
            )
            .annotate(
                count=Count("id")
            )
            .order_by(
                "-count",
                "violation"
            )
        )

        return Response(
            {
                "student": {
                    "id": student.id,
                    "student_id": student.student_id,
                    "first_name": student.first_name,
                    "last_name": student.last_name,
                    "course": student.course,
                    "year_level": student.year_level,
                    "email": student.email,
                },

                "cases": DisciplinaryCaseSerializer(
                    cases,
                    many=True
                ).data,

                "summary": list(summary),
            }
        )